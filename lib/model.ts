// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never the ceiling) and adds
// the pre-token protocols below the floor that the model itself rates highest: the early rows the
// radar exists to find. A protocol is pre-token when its record carries no token (no market cap,
// no CoinGecko id, no symbol); protocols whose token already trades are kept apart and shown with
// the market's own value, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base        = tvl_usd x BASE_MULTIPLE
//   growth      = clamp(change_7d, -50, 150) per cent
//   growthMult  = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity    = MATURITY_FLOOR + min(age_days, 1460) / 1460 x (1 - MATURITY_FLOOR)
//   chainBonus  = 1 + 0.03 x min(chains - 1, 5)
//   implied     = max(1, round(base x growthMult x maturity x chainBonus))
//
// TVL is the size of the protocol today. Seven-day growth is its direction. Age is how long it has
// run with no token: a protocol that has held billions for years without issuing one has more
// pent-up value to distribute than one listed last month. Chain count is reach: a protocol live on
// several chains has more surface to farm and more users to reward. The constants are the model's,
// stated in the dashboard and changeable in its sandbox. No protocol name is ever special-cased:
// the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_bonus_per_chain: number;
  chain_bonus_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.8,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.55,
  maturity_days: 1460,
  unknown_age_days: 270,
  chain_bonus_per_chain: 0.03,
  chain_bonus_max_chains: 5,
};

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by implied value. */
export const EARLY_ROWS = 260;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** One row of board.json: the ranked board's row. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  age_days: number | null;
  implied_value_usd: number;
  model: {
    base_multiple: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    chain_bonus: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

